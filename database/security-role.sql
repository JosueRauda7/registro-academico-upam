-- Ejecutar con psql -v app_password=... como administrador, sin registrar el valor.
SELECT 'CREATE ROLE upam_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE'
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'upam_app') \gexec
ALTER ROLE upam_app WITH PASSWORD :'app_password';
GRANT CONNECT ON DATABASE upam_academico TO upam_app;
GRANT USAGE ON SCHEMA public TO upam_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO upam_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO upam_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO upam_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO upam_app;
